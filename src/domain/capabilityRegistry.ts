/** Every capability the substrate declares. */
export const CAPABILITIES: readonly Capability[] = [...CORPUS_CAPABILITIES, ...SUBSTRATE_CAPABILITIES];

/** The capabilities of one area, for the navigator's grouping. */
export function capabilitiesOf(subsystem: string): readonly Capability[] {
  return CAPABILITIES.filter((capability) => capability.subsystem === subsystem);
}

/** Every area named by a capability, in a stable order. */
export const CAPABILITY_SUBSYSTEMS: readonly string[] =
  [...new Set(CAPABILITIES.map((capability) => capability.subsystem))].sort();

export function capabilityById(id: string): Capability | undefined {
  return CAPABILITIES.find((capability) => capability.id === id);
}

export function capabilityOfTool(toolName: string): Capability | undefined {
  const id = TOOL_CAPABILITY[toolName];
  return id === undefined ? undefined : capabilityById(id);
}
