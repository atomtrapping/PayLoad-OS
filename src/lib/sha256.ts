/**
 * SHA-256 with no runtime dependency, so a module that digests can be reached
 * from a browser bundle without dragging a Node polyfill behind it.
 *
 * Measured before this existed: the two frontier workbenches and the spatial
 * inquiry each imported one server module for a digest, and the bundler
 * answered with crypto-browserify and Buffer, 428 KB on each route, over
 * seventy percent of their client JavaScript. This is the whole of FIPS 180-4
 * in eighty lines, checked against node:crypto in sha256.test.ts on the
 * standard vectors, every length across the block and padding boundaries,
 * multi-byte text and a megabyte of noise. Inputs here are records of a few
 * kilobytes; nothing on this estate hashes at a rate where native speed would
 * be the difference.
 */

